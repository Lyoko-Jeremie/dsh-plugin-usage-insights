/**
 * Bundle the Client half into the Harness module-loader format.
 *
 * The browser artifact is a classic script that registers one lazy factory:
 * `window.__ModuleLoader__.load({ id, factory(require) })`, where the id equals
 * the package name (the Harness Client module system derives its row from the
 * bundle patch row). React and the JSX runtime are baseline platform modules
 * seeded by the shell, so they stay external and are resolved through the
 * `require` handed to the factory.
 */
import { build } from 'esbuild'
import { mkdir, readFile, writeFile } from 'node:fs/promises'
import { fileURLToPath } from 'node:url'
import { dirname, join } from 'node:path'

const root = dirname(dirname(fileURLToPath(import.meta.url)))
const pkg = JSON.parse(await readFile(join(root, 'package.json'), 'utf8'))

const result = await build({
  absWorkingDir: root,
  entryPoints: ['src/client/index.ts'],
  bundle: true,
  write: false,
  format: 'cjs',
  platform: 'browser',
  target: 'es2022',
  jsx: 'automatic',
  external: ['react', 'react-dom', 'react-dom/client', 'react/jsx-runtime'],
  legalComments: 'none',
  logLevel: 'warning',
})

const code = result.outputFiles[0].text
const banner = [
  `/* ${pkg.name} v${pkg.version} — generated by scripts/build.mjs; do not edit. */`,
  'window.__ModuleLoader__.load({',
  `  id: ${JSON.stringify(pkg.name)},`,
  '  factory(require) {',
  '    const module = { exports: {} };',
  '    const exports = module.exports;',
  '    (function (module, exports, require) {',
  '',
].join('\n')
const footer = [
  '',
  '    })(module, exports, require);',
  '    return module.exports;',
  '  },',
  '});',
  '',
].join('\n')

await mkdir(join(root, 'dist'), { recursive: true })
await writeFile(join(root, 'dist/client.js'), `${banner}${code}${footer}`)
console.log(`built dist/client.js (${(banner.length + code.length + footer.length) / 1024 | 0} KiB)`)
